-- ==============================================================================
-- MIGRATION: Bukti Digital Perjalanan (Proof of Visit) Blockchain - MeraTrip
-- Network Target: Ethereum Sepolia Testnet (Chain ID 11155111)
-- ==============================================================================
-- Menyimpan metadata sertifikat perjalanan terverifikasi kriptografis SHA-256.
-- PRIVASI: Data mentah PII (nama, email, no HP, rincian biaya, catatan rahasia)
-- DILARANG disimpan di kolom snapshot publik maupun dicatat ke smart contract.
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.trip_proofs (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    trip_id BIGINT REFERENCES public.trips(id) ON DELETE CASCADE,
    proof_id TEXT UNIQUE NOT NULL,
    proof_hash TEXT NOT NULL,
    payload_version TEXT DEFAULT '1.0.0' NOT NULL,
    snapshot_json TEXT NOT NULL,
    salt TEXT NOT NULL,
    chain_id BIGINT DEFAULT 11155111 NOT NULL,
    contract_address TEXT NOT NULL,
    tx_hash TEXT,
    status TEXT DEFAULT 'pending' NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Indeks performa tinggi
CREATE INDEX IF NOT EXISTS idx_trip_proofs_trip_id ON public.trip_proofs(trip_id);
CREATE INDEX IF NOT EXISTS idx_trip_proofs_user_id ON public.trip_proofs(user_id);
CREATE INDEX IF NOT EXISTS idx_trip_proofs_proof_id ON public.trip_proofs(proof_id);
CREATE INDEX IF NOT EXISTS idx_trip_proofs_status ON public.trip_proofs(status);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE public.trip_proofs ENABLE ROW LEVEL SECURITY;

-- 1. Pengguna hanya dapat membaca sertifikat milik akun mereka sendiri
CREATE POLICY "Users can view their own trip proofs"
    ON public.trip_proofs FOR SELECT
    USING (auth.uid() = user_id);

-- 2. Pengguna hanya dapat membuat sertifikat untuk akun mereka sendiri
CREATE POLICY "Users can insert their own trip proofs"
    ON public.trip_proofs FOR INSERT
    WITH CHECK (auth.uid() = user_id);

-- 3. Pengguna atau Edge Function dapat memperbarui status sertifikat mereka
CREATE POLICY "Users can update their own trip proofs"
    ON public.trip_proofs FOR UPDATE
    USING (auth.uid() = user_id);

-- 4. Pengguna dapat menghapus bukti jika trip mereka dihapus
CREATE POLICY "Users can delete their own trip proofs"
    ON public.trip_proofs FOR DELETE
    USING (auth.uid() = user_id);
