-- 1. TABEL PROFILES (Data Akun & Gamifikasi Pengguna)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT,
    email TEXT,
    avatar_url TEXT,
    phone TEXT,
    jagawana_level TEXT DEFAULT 'Penjelajah Pemula',
    jagawana_exp INT DEFAULT 0,
    is_biometric_enabled BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. TABEL DESTINATIONS (Destinasi Wisata Terverifikasi Lereng Merapi)
CREATE TABLE IF NOT EXISTS public.destinations (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    description TEXT,
    category_id INT DEFAULT 1,
    category_name TEXT DEFAULT 'Wisata Alam',
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    elevation_mdpl INT DEFAULT 0,
    ticket_price NUMERIC DEFAULT 0,
    ticket_price_label TEXT DEFAULT 'Tiket Masuk',
    opening_hours TEXT DEFAULT '06.00 - 17.00 WIB',
    estimated_duration TEXT DEFAULT '45 - 60 Menit',
    temperature_range TEXT DEFAULT '18°C - 24°C',
    address TEXT,
    image_url TEXT,
    rating NUMERIC DEFAULT 4.8,
    review_count INT DEFAULT 500,
    facilities TEXT[] DEFAULT ARRAY['Area Parkir', 'Toilet', 'Mushola'],
    best_visiting_time TEXT DEFAULT 'Pukul 05.30 - 08.00 WIB untuk pemandangan puncak jernih',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. TABEL TRIPS (Rencana Perjalanan Wisata Pengguna)
CREATE TABLE IF NOT EXISTS public.trips (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    trip_name TEXT NOT NULL,
    start_date TEXT NOT NULL,
    participant_count INT DEFAULT 2,
    target_budget NUMERIC DEFAULT 400000,
    total_estimated_cost NUMERIC DEFAULT 0,
    status TEXT DEFAULT 'upcoming', -- 'upcoming', 'draft', 'completed'
    reminder_enabled BOOLEAN DEFAULT TRUE,
    is_saved_offline BOOLEAN DEFAULT TRUE,
    banner_image_url TEXT,
    items JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ==============================================================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================

-- Aktifkan RLS pada seluruh tabel
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.destinations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trips ENABLE ROW LEVEL SECURITY;

-- Policy untuk PROFILES: Pengguna hanya boleh melihat dan mengedit profilnya sendiri
DROP POLICY IF EXISTS "Users can view own profile" ON public.profiles;
CREATE POLICY "Users can view own profile"
    ON public.profiles FOR SELECT
    USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can insert own profile" ON public.profiles;
CREATE POLICY "Users can insert own profile"
    ON public.profiles FOR INSERT
    WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
CREATE POLICY "Users can update own profile"
    ON public.profiles FOR UPDATE
    USING (auth.uid() = id);

-- Policy untuk DESTINATIONS: Publik boleh membaca (SELECT), perubahan dibatasi admin
DROP POLICY IF EXISTS "Destinations are publicly viewable" ON public.destinations;
CREATE POLICY "Destinations are publicly viewable"
    ON public.destinations FOR SELECT
    USING (true);

-- Policy untuk TRIPS: Pengguna hanya boleh membaca, membuat, mengubah, & menghapus trip miliknya sendiri
DROP POLICY IF EXISTS "Users can view own trips" ON public.trips;
CREATE POLICY "Users can view own trips"
    ON public.trips FOR SELECT
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert own trips" ON public.trips;
CREATE POLICY "Users can insert own trips"
    ON public.trips FOR INSERT
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update own trips" ON public.trips;
CREATE POLICY "Users can update own trips"
    ON public.trips FOR UPDATE
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete own trips" ON public.trips;
CREATE POLICY "Users can delete own trips"
    ON public.trips FOR DELETE
    USING (auth.uid() = user_id);

-- ==============================================================================
-- 5. TRIGGER OTOMATIS: BUAT PROFIL SAAT USER MENDAFTAR (AUTH.USERS)
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, name, avatar_url)
    VALUES (
        new.id,
        new.email,
        COALESCE(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
        new.raw_user_meta_data->>'avatar_url'
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

