-- ==============================================================================
-- MIGRATION: Mode Perjalanan Aktif & Pencatatan Pengeluaran (MeraTrip)
-- ==============================================================================
-- Menambahkan kolom status aktif, durasi perjalanan, dan tabel pengeluaran aktual
-- beserta kebijakan Row Level Security (RLS).
-- ==============================================================================

-- 1. Tambahkan kolom pendukung di tabel public.trips
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS total_actual_cost NUMERIC DEFAULT 0;
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS started_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS completed_at TIMESTAMP WITH TIME ZONE;

-- 2. Buat tabel public.trip_expenses
CREATE TABLE IF NOT EXISTS public.trip_expenses (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    trip_id BIGINT REFERENCES public.trips(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    destination_id BIGINT REFERENCES public.destinations(id) ON DELETE SET NULL,
    destination_name TEXT,
    category TEXT NOT NULL,
    amount NUMERIC NOT NULL CHECK (amount >= 0),
    notes TEXT,
    spent_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Indeks untuk query performa tinggi
CREATE INDEX IF NOT EXISTS idx_trip_expenses_trip_id ON public.trip_expenses(trip_id);
CREATE INDEX IF NOT EXISTS idx_trip_expenses_user_id ON public.trip_expenses(user_id);

-- 3. Row Level Security (RLS) pada tabel trip_expenses
ALTER TABLE public.trip_expenses ENABLE ROW LEVEL SECURITY;

-- Pengguna hanya dapat melihat pengeluaran milik akun mereka sendiri
CREATE POLICY "Users can view their own trip expenses"
    ON public.trip_expenses FOR SELECT
    USING (auth.uid() = user_id);

-- Pengguna hanya dapat menambahkan pengeluaran untuk akun mereka sendiri
CREATE POLICY "Users can insert their own trip expenses"
    ON public.trip_expenses FOR INSERT
    WITH CHECK (auth.uid() = user_id);

-- Pengguna hanya dapat memperbarui pengeluaran milik mereka sendiri
CREATE POLICY "Users can update their own trip expenses"
    ON public.trip_expenses FOR UPDATE
    USING (auth.uid() = user_id);

-- Pengguna hanya dapat menghapus pengeluaran milik mereka sendiri
CREATE POLICY "Users can delete their own trip expenses"
    ON public.trip_expenses FOR DELETE
    USING (auth.uid() = user_id);
