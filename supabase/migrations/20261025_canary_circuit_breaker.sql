-- ==============================================================================
-- MIGRATION: Single-Use Canary Circuit Breaker & State Machine
-- Target: Ethereum Sepolia Canary Transaction (Trip ID 50)
-- ==============================================================================
-- Menjamin secara atomik di level database PostgreSQL bahwa fase canary hanya
-- mengizinkan tepat SATU transaksi on-chain untuk dieksekusi.
-- Mencegah race condition, double broadcast, dan nonce collision di multi-instance.
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.canary_claims (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    canary_scope TEXT UNIQUE NOT NULL DEFAULT 'CANARY_TRIP_50',
    trip_id BIGINT NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    proof_id TEXT NOT NULL,
    proof_hash TEXT NOT NULL,
    idempotency_key TEXT NOT NULL,
    execution_token UUID NOT NULL DEFAULT gen_random_uuid(),
    state TEXT NOT NULL DEFAULT 'reserved',
    -- States: 'reserved', 'broadcast_attempted', 'tx_known', 'confirmed', 'failed_recoverable', 'recovery_required'
    tx_hash TEXT,
    relayer_nonce BIGINT,
    conservative_max_fee_gwei NUMERIC,
    gas_limit BIGINT,
    error_message TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Indeks performa & audit
CREATE INDEX IF NOT EXISTS idx_canary_claims_scope ON public.canary_claims(canary_scope);
CREATE INDEX IF NOT EXISTS idx_canary_claims_trip_id ON public.canary_claims(trip_id);
CREATE INDEX IF NOT EXISTS idx_canary_claims_state ON public.canary_claims(state);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE public.canary_claims ENABLE ROW LEVEL SECURITY;

-- 1. Policy: Hanya service role / Edge Function yang dapat memanipulasi klaim canary
DROP POLICY IF EXISTS "Service role full access to canary claims" ON public.canary_claims;
CREATE POLICY "Service role full access to canary claims"
    ON public.canary_claims
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

-- 2. Policy: Authenticated users can view their own canary claim (READ ONLY)
DROP POLICY IF EXISTS "Users can view their own canary claims" ON public.canary_claims;
CREATE POLICY "Users can view their own canary claims"
    ON public.canary_claims
    FOR SELECT
    TO authenticated
    USING (auth.uid() = user_id);

-- 3. RPC Atomik: acquire_or_get_canary_claim
-- SECURITY DEFINER dengan search_path dipin secara ketat ke public, pg_temp
-- ATURAN KEAMANAN:
-- Tepat SATU pemenang INSERT yang memperoleh has_execution_permit = true ('execute_broadcast') dan execution_token.
-- Seluruh retry / existing claim TIDAK PERNAH memperoleh has_execution_permit dan execution_token selalu NULL.
CREATE OR REPLACE FUNCTION public.acquire_or_get_canary_claim(
    p_canary_scope TEXT,
    p_trip_id BIGINT,
    p_user_id UUID,
    p_proof_id TEXT,
    p_proof_hash TEXT,
    p_idempotency_key TEXT
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_existing public.canary_claims%ROWTYPE;
    v_new public.canary_claims%ROWTYPE;
BEGIN
    -- 1. Periksa apakah scope canary sudah pernah diklaim
    SELECT * INTO v_existing FROM public.canary_claims WHERE canary_scope = p_canary_scope;
    IF FOUND THEN
        -- Scope sudah pernah diklaim.
        -- JAMINAN KEAMANAN: Existing claim TIDAK PERNAH memberikan hak eksekusi broadcast.
        -- execution_token tidak pernah dibagikan kepada pemanggil rekonsiliasi / retry.
        IF v_existing.trip_id = p_trip_id AND v_existing.proof_id = p_proof_id THEN
            RETURN jsonb_build_object(
                'status', 'existing_claim',
                'is_owner', true,
                'has_execution_permit', false,
                'action', 'reconcile_only',
                'execution_token', NULL,
                'claim', to_jsonb(v_existing) - 'execution_token'
            );
        ELSE
            -- Scope sudah diklaim oleh trip lain atau proof lain: tolak tegas!
            RETURN jsonb_build_object(
                'status', 'scope_exhausted',
                'is_owner', false,
                'has_execution_permit', false,
                'action', 'reject',
                'execution_token', NULL,
                'claim', to_jsonb(v_existing) - 'execution_token'
            );
        END IF;
    END IF;

    -- 2. Coba insert secara atomik
    BEGIN
        INSERT INTO public.canary_claims (
            canary_scope, trip_id, user_id, proof_id, proof_hash, idempotency_key, state
        ) VALUES (
            p_canary_scope, p_trip_id, p_user_id, p_proof_id, p_proof_hash, p_idempotency_key, 'reserved'
        ) RETURNING * INTO v_new;

        -- TEPAT SATU pemenang INSERT yang memperoleh hak eksekusi broadcast dan execution_token
        RETURN jsonb_build_object(
            'status', 'acquired',
            'is_owner', true,
            'has_execution_permit', true,
            'action', 'execute_broadcast',
            'execution_token', v_new.execution_token,
            'claim', to_jsonb(v_new)
        );
    EXCEPTION WHEN unique_violation THEN
        -- Race condition: request konkuren lain memenangkan INSERT pada saat yang sama
        SELECT * INTO v_existing FROM public.canary_claims WHERE canary_scope = p_canary_scope;
        RETURN jsonb_build_object(
            'status', CASE WHEN v_existing.trip_id = p_trip_id AND v_existing.proof_id = p_proof_id THEN 'existing_claim' ELSE 'scope_exhausted' END,
            'is_owner', (v_existing.trip_id = p_trip_id AND v_existing.proof_id = p_proof_id),
            'has_execution_permit', false,
            'action', CASE WHEN v_existing.trip_id = p_trip_id AND v_existing.proof_id = p_proof_id THEN 'reconcile_only' ELSE 'reject' END,
            'execution_token', NULL,
            'claim', to_jsonb(v_existing) - 'execution_token'
        );
    END;
END;
$$;

-- 4. RPC Atomik: transition_canary_claim_state (State Machine Compare-And-Swap)
-- Menjamin transisi state canary claim terjadi secara atomik dengan row lock (SELECT FOR UPDATE).
-- ATOMIC AUTHORIZATION: Transisi dari 'reserved' ke 'broadcast_attempted' WAJIB memvalidasi execution_token.
CREATE OR REPLACE FUNCTION public.transition_canary_claim_state(
    p_canary_scope TEXT,
    p_expected_state TEXT,
    p_new_state TEXT,
    p_execution_token UUID DEFAULT NULL,
    p_tx_hash TEXT DEFAULT NULL,
    p_relayer_nonce BIGINT DEFAULT NULL,
    p_gas_limit BIGINT DEFAULT NULL,
    p_conservative_max_fee_gwei NUMERIC DEFAULT NULL,
    p_error_message TEXT DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_current public.canary_claims%ROWTYPE;
BEGIN
    -- 1. Lock baris secara eksklusif untuk update (pessimistic lock)
    SELECT * INTO v_current 
    FROM public.canary_claims 
    WHERE canary_scope = p_canary_scope 
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'claim_not_found',
            'canary_scope', p_canary_scope
        );
    END IF;

    -- 2. Validasi Compare-And-Swap (CAS): state saat ini HARUS sama dengan expected_state
    IF v_current.state <> p_expected_state THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'state_mismatch',
            'current_state', v_current.state,
            'expected_state', p_expected_state,
            'claim', to_jsonb(v_current) - 'execution_token'
        );
    END IF;

    -- 3. JAMINAN ATOMIC AUTHORIZATION:
    -- Transisi dari 'reserved' ke 'broadcast_attempted' WAJIB memvalidasi p_execution_token yang cocok.
    -- Mencegah request non-owner, retry, atau stale caller memenangkan hak broadcast.
    IF p_expected_state = 'reserved' THEN
        IF p_execution_token IS NULL OR v_current.execution_token <> p_execution_token THEN
            RETURN jsonb_build_object(
                'success', false,
                'error', 'invalid_execution_token',
                'canary_scope', p_canary_scope,
                'current_state', v_current.state
            );
        END IF;
    END IF;

    -- 4. Update atomik
    UPDATE public.canary_claims
    SET 
        state = p_new_state,
        tx_hash = COALESCE(p_tx_hash, v_current.tx_hash),
        relayer_nonce = COALESCE(p_relayer_nonce, v_current.relayer_nonce),
        gas_limit = COALESCE(p_gas_limit, v_current.gas_limit),
        conservative_max_fee_gwei = COALESCE(p_conservative_max_fee_gwei, v_current.conservative_max_fee_gwei),
        error_message = COALESCE(p_error_message, v_current.error_message),
        updated_at = TIMEZONE('utc'::text, NOW())
    WHERE canary_scope = p_canary_scope
    RETURNING * INTO v_current;

    RETURN jsonb_build_object(
        'success', true,
        'previous_state', p_expected_state,
        'current_state', p_new_state,
        'claim', to_jsonb(v_current) - 'execution_token'
    );
END;
$$;

-- 5. Hak Akses & Privileges: HANYA service_role yang berhak mengeksekusi RPC ini.
-- Mencegah authenticated user memanggil langsung via PostgREST untuk membajak canary slot atau memanipulasi state.
REVOKE ALL ON FUNCTION public.acquire_or_get_canary_claim(TEXT, BIGINT, UUID, TEXT, TEXT, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.acquire_or_get_canary_claim(TEXT, BIGINT, UUID, TEXT, TEXT, TEXT) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.acquire_or_get_canary_claim(TEXT, BIGINT, UUID, TEXT, TEXT, TEXT) TO service_role;

REVOKE ALL ON FUNCTION public.transition_canary_claim_state(TEXT, TEXT, TEXT, UUID, TEXT, BIGINT, BIGINT, NUMERIC, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.transition_canary_claim_state(TEXT, TEXT, TEXT, UUID, TEXT, BIGINT, BIGINT, NUMERIC, TEXT) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.transition_canary_claim_state(TEXT, TEXT, TEXT, UUID, TEXT, BIGINT, BIGINT, NUMERIC, TEXT) TO service_role;

